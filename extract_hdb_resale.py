#!/usr/bin/env python3
"""
================================================================================
HDB RESALE FLAT PRICES DATA EXTRACTION & INGESTION PIPELINE
================================================================================
Author: Senior Data Engineer Candidate
Target Source: Singapore Government Open Data API (data.gov.sg CKAN datastore)
Format: Optimized Parquet with Snappy Compression & Atomic POSIX Writes

Pipeline Capabilities:
  1. Programmatic extraction for any specified month (YYYY-MM).
  2. Resilient API pagination via limit/offset against the CKAN datastore.
  3. Exponential backoff with full randomized jitter and Retry-After header support.
  4. Semi-structured JSON flattening, type coercion, and schema drift preservation.
  5. Deterministic surrogate key hashing (SHA-256) for absolute deduplication.
  6. Idempotent local storage writing with atomic swap (zero corrupt/partial files).
  7. Production-grade Snowflake loading strategy with in-depth inline commentary.
================================================================================
"""

import argparse
from datetime import datetime
import logging
import os
import sys
from pathlib import Path

# Ensure src modules are resolvable
sys.path.insert(0, str(Path(__file__).resolve().parent))

from src.client import APIClient
from src.config import BackoffConfig, PipelineConfig
from src.extractor import HDBResaleExtractor
from src.storage import ParquetStorageWriter
from src.transformer import HDBResaleTransformer

# Configure structured logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s - %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
)
logger = logging.getLogger("extract_hdb_resale")


# ==============================================================================
# PRODUCTION SNOWFLAKE LOADING STRATEGY (INLINE ARCHITECTURAL BLUEPRINT)
# ==============================================================================
# In a high-throughput, mission-critical enterprise data warehouse, landing
# files directly from Python scripts into relational tables requires a robust,
# multi-hop medallion architecture (Landing -> Bronze -> Silver -> Gold).
#
# Below is the production Snowflake strategy designed for this pipeline:
#
# 1. STORAGE INTEGRATION & EXTERNAL CLOUD STAGING:
#    - Cloud Storage: Parquet files generated by this pipeline are synchronized
#      to an enterprise object store (e.g. AWS S3: `s3://data-lake/raw/hdb_resale/year=YYYY/month=MM/`).
#    - Security: Use a Snowflake `STORAGE INTEGRATION` object rather than long-lived
#      AWS IAM access keys. This uses an AWS IAM Role with External ID trust
#      delegation, satisfying strict zero-trust security compliance.
#    - External Stage: `CREATE STAGE raw.hdb_resale_stage ... FILE_FORMAT = (TYPE = PARQUET)`.
#
# 2. BRONZE LAYER (RAW SEMI-STRUCTURED INGESTION & ZERO DATA LOSS):
#    - Table Definition: `raw.bronze_hdb_resale (record_hash, month, raw_payload VARIANT, ...)`.
#    - Ingestion Engine: Use SNOWPIPE with `AUTO_INGEST = TRUE` triggered via
#      cloud storage notifications (Amazon SQS / EventBridge).
#    - Schema Drift Protection: By preserving the raw record inside a `VARIANT`
#      column (`raw_payload`), any upstream schema additions (e.g. new API attributes
#      introduced by HDB) or column dropouts (e.g. `remaining_lease` missing in older
#      epochs) are captured losslessly without failing the ingestion pipe.
#
# 3. IDEMPOTENT CONVERSION TO SILVER LAYER (CONFORMED TRANSACTIONS):
#    - Deduplication Key: This script computes a deterministic SHA-256 surrogate
#      hash `_record_hash` based on the natural transaction business key:
#      (month, town, flat_type, block, street_name, storey_range, floor_area, resale_price).
#    - Idempotent Loading: An orchestrated `MERGE INTO silver.hdb_resale_prices`
#      is executed (via dbt, Apache Airflow, or Snowflake Tasks):
#          MERGE INTO silver.hdb_resale_prices tgt
#          USING bronze.hdb_resale_view src
#          ON tgt.record_hash = src.record_hash
#          WHEN MATCHED THEN UPDATE SET ...
#          WHEN NOT MATCHED THEN INSERT ...;
#    - If a data engineer re-runs an extraction job for a past month, the `MERGE`
#      statement safely updates the state without creating duplicate records.
#
# 4. GOLD LAYER & ANALYTICAL PERFORMANCE OPTIMIZATION:
#    - Snowflake Dynamic Tables: `CREATE DYNAMIC TABLE gold.hdb_monthly_trends ...`
#      aggregates monthly transaction counts, median price, and price/sqm by town.
#    - Micro-Partition Pruning & Clustering: Cluster Silver and Gold tables by
#      `(transaction_month, town)` to enable sub-second query latency for BI tools
#      like Tableau and Power BI.
# ==============================================================================


def run_pipeline(
    month: str,
    output_dir: str = "data/output",
    batch_size: int = 1000,
    max_retries: int = 5,
    custom_resource_id: str = None,
) -> Path:
    """
    Executes the end-to-end extraction, transformation, and idempotent Parquet write.

    Args:
        month: Month string formatted as YYYY-MM.
        output_dir: Directory where the resulting Parquet file will be stored.
        batch_size: API pagination page size (records per request).
        max_retries: Maximum exponential backoff retries on rate limits or errors.
        custom_resource_id: Optional custom CKAN resource ID override.

    Returns:
        Path to the committed local Parquet file.
    """
    start_time = datetime.now()
    logger.info("=" * 70)
    logger.info(f"Starting HDB Resale Extraction Pipeline for Month: {month}")
    logger.info("=" * 70)

    # 1. Initialize Configuration
    backoff_cfg = BackoffConfig(
        max_retries=max_retries,
        base_delay=1.0,
        max_delay=60.0,
        backoff_factor=2.0,
        jitter=True,
        timeout_seconds=30,
    )

    pipeline_cfg = PipelineConfig(
        target_month=month,
        resource_id=custom_resource_id,
        batch_size=batch_size,
        output_dir=output_dir,
        backoff=backoff_cfg,
    )
    logger.info(f"Resolved CKAN Resource ID: {pipeline_cfg.resource_id}")

    # 2. Extract Data via Resilient Client & Pagination
    #    (Handles HTTP 429, 5xx with full jitter exponential backoff)
    client = APIClient(backoff_config=backoff_cfg)
    try:
        extractor = HDBResaleExtractor(config=pipeline_cfg, client=client)
        raw_records, extract_meta = extractor.fetch_all_records()
    finally:
        client.close()

    total_extracted = len(raw_records)
    logger.info(f"Extraction phase finished. Fetched {total_extracted} records.")

    if total_extracted == 0:
        logger.warning(
            f"No records found for month '{month}'. "
            "Please check if the month has published data on data.gov.sg."
        )

    # 3. Transform, Flatten, Type Coerce & Deduplicate
    #    - Flattens nested JSON structures into tabular format.
    #    - Computes deterministic SHA-256 surrogate keys for idempotent warehousing.
    #    - Enforces PyArrow strict data types for high-performance columnar storage.
    transformer = HDBResaleTransformer(resource_id=pipeline_cfg.resource_id)
    arrow_table, transform_meta = transformer.transform(raw_records)
    logger.info(
        f"Transformation finished. Output rows: {transform_meta['output_rows']} "
        f"(Deduplicated {transform_meta['duplicates_removed']} duplicate keys)."
    )

    # 4. Atomic, Idempotent Storage Commit
    #    - Writes to an ephemeral hidden file (.tmp.<uuid>).
    #    - Performs an atomic POSIX replace into the final Parquet file.
    #    - Verifies file integrity and logs SHA-256 checksum for audit trails.
    storage = ParquetStorageWriter(base_output_dir=pipeline_cfg.output_dir)
    target_path, file_meta = storage.write_atomic_parquet(arrow_table, month=month)

    duration = (datetime.now() - start_time).total_seconds()
    logger.info("=" * 70)
    logger.info("PIPELINE EXECUTION SUMMARY:")
    logger.info(f"  Target Month:       {month}")
    logger.info(f"  Parquet File:       {file_meta['file_path']}")
    logger.info(f"  Total Rows:         {file_meta['row_count']}")
    logger.info(f"  File Size:          {file_meta['file_size_kb']} KB ({file_meta['file_size_bytes']} bytes)")
    logger.info(f"  SHA-256 Checksum:   {file_meta['sha256_checksum']}")
    logger.info(f"  Elapsed Time:       {duration:.2f} seconds")
    logger.info("=" * 70)

    # ==========================================================================
    # SNOWFLAKE LOADING NEXT STEPS (OPERATIONAL CHECKLIST):
    #   1. Sync local Parquet file to S3:
    #      aws s3 cp {file_meta['file_path']} s3://my-bucket/raw/hdb_resale/{file_meta['file_name']}
    #   2. Trigger Snowpipe or run idempotent COPY INTO / MERGE:
    #      (See sql/03_silver_gold_merge_transforms.sql for production DDL/DML)
    # ==========================================================================

    return target_path


def parse_arguments() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Programmatically extract HDB Resale Flat Prices from data.gov.sg with exponential backoff and Parquet output.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--month",
        type=str,
        default="2024-01",
        help="Target month to extract in YYYY-MM format (e.g. 2024-01, 2023-12).",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data/output",
        help="Local directory where the Parquet file will be atomically stored.",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=1000,
        help="Number of records to fetch per pagination API call (maximum 1000).",
    )
    parser.add_argument(
        "--max-retries",
        type=int,
        default=5,
        help="Maximum exponential backoff retry attempts on HTTP 429 / 5xx.",
    )
    parser.add_argument(
        "--resource-id",
        type=str,
        default=None,
        help="Optional custom data.gov.sg CKAN resource ID override.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable detailed debug-level logging.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_arguments()
    if args.verbose:
        logger.setLevel(logging.DEBUG)

    try:
        run_pipeline(
            month=args.month,
            output_dir=args.output_dir,
            batch_size=args.batch_size,
            max_retries=args.max_retries,
            custom_resource_id=args.resource_id,
        )
    except Exception as exc:
        logger.error(f"Pipeline execution failed: {exc}", exc_info=args.verbose)
        sys.exit(1)
